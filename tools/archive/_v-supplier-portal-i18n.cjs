async function main() {
  const missing = {}
  let checked = 0
  const sameByLoc = {}
  for (const loc of LOCALES) {
    const file = path.join(ROOT, 'frontend', 'src', 'i18n', 'locales', `${loc}.js`)
    const mod = await import('file:///' + file.replace(/\\/g, '/'))
    const biz = (mod.default && mod.default.biz) || {}
    missing[loc] = []
    const same = []
    for (const k of KEYS) {
      checked++
      const v = biz[k]
      if (!v) { missing[loc].push(k); continue }
      // 译文 == 中文原键 **不算缺**:日语/繁体本身就是汉字语言,「行数/操作/数量」这类词
      // 在目标语言里写法与简体中文相同(不是漏翻),单独计入"同形"统计,不判失败。
      if (v === k) same.push(k)
    }
    sameByLoc[loc] = same
  }
  let bad = 0
  for (const loc of LOCALES) {
    const m = missing[loc]
    if (m.length) {
      bad++
      console.log(`[FAIL] ${loc} 缺 ${m.length} 条: ${m.slice(0, 8).join(' / ')}${m.length > 8 ? ' …' : ''}`)
    } else {
      const same = sameByLoc[loc] || []
      console.log(`[PASS] ${loc}:${KEYS.length} 条全部有译文${same.length ? `(其中 ${same.length} 条与中文同形:${same.slice(0, 6).join('/')}${same.length > 6 ? '…' : ''})` : ''}`)
    }
  }
  console.log(`\n=== ${KEYS.length} 键 × ${LOCALES.length} 语言 = ${checked} 次检查;失败语言 ${bad} ===`)
  process.exit(bad ? 1 : 0)
}

main().catch((e) => { console.error('[FATAL]', e); process.exit(2) })
