SET NOCOUNT ON;
IF OBJECT_ID('tempdb..#d4') IS NOT NULL DROP TABLE #d4;
CREATE TABLE #d4(t sysname);
GO
DECLARE @t sysname;
DECLARE cur CURSOR LOCAL FAST_FORWARD FOR SELECT name FROM sys.tables WHERE name IN (N'plang',N'scjl');
OPEN cur;
FETCH NEXT FROM cur INTO @t;
WHILE @@FETCH_STATUS = 0
BEGIN
  INSERT #d4 VALUES(@t);
  FETCH NEXT FROM cur INTO @t;
END
CLOSE cur; DEALLOCATE cur;
SELECT t FROM #d4 ORDER BY t;
GO
