SET NOCOUNT ON;
SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'yj_panel' ORDER BY ORDINAL_POSITION;
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE 'qc[_]%insp%' ORDER BY TABLE_NAME;
SELECT c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.COLUMN_NAME IN (N'合格数量', N'不合格数量')
ORDER BY c.TABLE_NAME;
