FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME IN ('qc_catalog','qc_catalog_detail','qc_insp','qc_insp_detail','qc_insp_rec','qc_insp_rec_detail')
ORDER BY TABLE_NAME, ORDINAL_POSITION;
