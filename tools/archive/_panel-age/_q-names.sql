SET NOCOUNT ON;
SELECT p.panel_code, p.panel_name, p.category, p.mode, ISNULL(p.line_table,'') AS line_table, ISNULL(p.head_table,'') AS head_table
FROM yj_panel p
WHERE p.panel_code IN ('QC_OP','QC_RECORD','QC_DISPOSAL','ROD_RETURN','LOT_TRACE','SALES_ORDER_DETAIL','SALES_ORDER_STATS','PURCHASE_IN_DETAIL','FINISH_IN_DETAIL','OTHER_IN_DETAIL','OUTSOURCE_IN_DETAIL','SALE_OUT_DETAIL','MATERIAL_OUT_DETAIL','OTHER_OUT_DETAIL','OUTSOURCE_ISSUE_DETAIL','PURCHASE_IN_STATS','FINISH_IN_STATS','OTHER_IN_STATS','OUTSOURCE_IN_STATS','SALE_OUT_STATS','MATERIAL_OUT_STATS','OTHER_OUT_STATS','OUTSOURCE_ISSUE_STATS','STOCK_BALANCE','STOCK_SUMMARY')
ORDER BY p.panel_code;
GO
