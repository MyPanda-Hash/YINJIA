SET NOCOUNT ON;
SELECT COUNT(*) AS docs,
  SUM(CASE WHEN ISNULL(加工单号,N'')<>N'' THEN 1 ELSE 0 END) AS 工单号,
  SUM(CASE WHEN ISNULL(领用人,N'')<>N'' THEN 1 ELSE 0 END) AS 领用人,
  SUM(CASE WHEN ISNULL(出库类别,N'')<>N'' THEN 1 ELSE 0 END) AS 退料类别,
  SUM(CASE WHEN ISNULL(来源单号,N'')<>N'' THEN 1 ELSE 0 END) AS 来源单号,
  SUM(CASE WHEN ISNULL(部门编码,N'')<>N'' THEN 1 ELSE 0 END) AS 部门编码,
  SUM(CASE WHEN ISNULL(经手人编码,N'')<>N'' THEN 1 ELSE 0 END) AS 经手人编码,
  SUM(CASE WHEN ISNULL(是否已转ERP,N'')<>N'' THEN 1 ELSE 0 END) AS 是否已转ERP,
  SUM(CASE WHEN ISNULL(ERP单号,N'')<>N'' THEN 1 ELSE 0 END) AS ERP单号,
  SUM(CASE WHEN ISNULL(业务类型,N'')<>N'' THEN 1 ELSE 0 END) AS 业务类型
FROM dbo.bd_material_ret WHERE ISNULL(asp_cancel,N'N')<>N'Y';