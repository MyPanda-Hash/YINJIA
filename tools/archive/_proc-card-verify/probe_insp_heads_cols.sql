/* D) 静态校验:三张现役检验单头/明细的实际列(每个 SELECT 一张表,SqlRunner 每结果集最多 50 行) */
SET NOCOUNT ON;
SELECT N'qc_first_insp_head' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_first_insp_head' ORDER BY ORDINAL_POSITION;
GO
SELECT N'qc_first_insp_detail' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_first_insp_detail' ORDER BY ORDINAL_POSITION;
GO
SELECT N'qc_proc_insp_head' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_proc_insp_head' ORDER BY ORDINAL_POSITION;
GO
SELECT N'qc_proc_insp_detail' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_proc_insp_detail' ORDER BY ORDINAL_POSITION;
GO
SELECT N'qc_asm_insp_head' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_asm_insp_head' ORDER BY ORDINAL_POSITION;
GO
SELECT N'qc_asm_insp_detail' AS 表, COLUMN_NAME AS 列 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = N'qc_asm_insp_detail' ORDER BY ORDINAL_POSITION;
GO
SELECT N'表存在性' AS 项,
       CASE WHEN OBJECT_ID(N'dbo.qc_first_insp_head',N'U') IS NULL THEN 0 ELSE 1 END AS 首件头,
       CASE WHEN OBJECT_ID(N'dbo.qc_proc_insp_head',N'U') IS NULL THEN 0 ELSE 1 END AS 制程头,
       CASE WHEN OBJECT_ID(N'dbo.qc_asm_insp_head',N'U') IS NULL THEN 0 ELSE 1 END AS 组装头;
GO
