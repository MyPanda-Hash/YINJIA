SET NOCOUNT ON;
PRINT '== yj_schema_log 结构 ==';
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='yj_schema_log' ORDER BY ORDINAL_POSITION;
GO
PRINT '== 最近 5 行 ==';
SELECT TOP 5 * FROM yj_schema_log ORDER BY id DESC;
GO
PRINT '== MANUAL 形式的既有登记 ==';
SELECT TOP 5 * FROM yj_schema_log WHERE content_hash LIKE N'MANUAL-%' ORDER BY id DESC;
