SET NOCOUNT ON;
SELECT 'SO' AS t, COUNT(*) AS 总行, SUM(CASE WHEN 行号 IS NULL THEN 1 ELSE 0 END) AS 空行号,
       COUNT(DISTINCT CASE WHEN 行号 IS NULL THEN 单据编号 END) AS 空行号单数 FROM bl_so_order;
GO
SELECT 'PU' AS t, COUNT(*) AS 总行, SUM(CASE WHEN ISNULL(LTRIM(RTRIM(CAST(行号 AS nvarchar(50)))),N'')=N'' THEN 1 ELSE 0 END) AS 空行号,
       COUNT(DISTINCT CASE WHEN ISNULL(LTRIM(RTRIM(CAST(行号 AS nvarchar(50)))),N'')=N'' THEN 单据编号 END) AS 空行号单数 FROM bl_pu_order;
GO
SELECT COUNT(*) AS SO重复单数 FROM (SELECT 单据编号 FROM bl_so_order GROUP BY 单据编号 HAVING COUNT(*) <> COUNT(DISTINCT ISNULL(行号,-1))) t;
GO
SELECT COUNT(*) AS PU行号重复单数 FROM (SELECT 单据编号 FROM bl_pu_order GROUP BY 单据编号 HAVING COUNT(*) <> COUNT(DISTINCT ISNULL(CAST(行号 AS nvarchar(50)),N''))) t;
