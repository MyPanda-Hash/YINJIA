SET NOCOUNT ON;
PRINT '=== 全库 kucun 批号分布 ===';
SELECT CASE WHEN lot_no IS NULL THEN N'NULL' WHEN RTRIM(lot_no)='' THEN N'空串' WHEN RTRIM(lot_no)=N'PC0000' THEN N'PC0000' ELSE N'真实批号' END AS 类别, COUNT(*) 行数
FROM kucun GROUP BY CASE WHEN lot_no IS NULL THEN N'NULL' WHEN RTRIM(lot_no)='' THEN N'空串' WHEN RTRIM(lot_no)=N'PC0000' THEN N'PC0000' ELSE N'真实批号' END;
PRINT '=== inh 流水批号分布 ===';
SELECT CASE WHEN 批号 IS NULL THEN N'NULL' WHEN RTRIM(批号)='' THEN N'空串' WHEN RTRIM(批号)=N'PC0000' THEN N'PC0000' ELSE N'真实批号' END AS 类别, COUNT(*) 行数
FROM inh GROUP BY CASE WHEN 批号 IS NULL THEN N'NULL' WHEN RTRIM(批号)='' THEN N'空串' WHEN RTRIM(批号)=N'PC0000' THEN N'PC0000' ELSE N'真实批号' END;
