SET NOCOUNT ON;
SELECT DB_NAME() AS db, COUNT(*) AS docs,
  SUM(CASE WHEN ISNULL(客户,N'')<>N'' THEN 1 ELSE 0 END) AS 客户,
  SUM(CASE WHEN ISNULL(客户编码,N'')<>N'' THEN 1 ELSE 0 END) AS 客户编码,
  SUM(CASE WHEN ISNULL(销售订单号,N'')<>N'' THEN 1 ELSE 0 END) AS 销售订单号,
  SUM(CASE WHEN ISNULL(出库类别,N'')<>N'' THEN 1 ELSE 0 END) AS 退货类别,
  SUM(CASE WHEN ISNULL(部门,N'')<>N'' THEN 1 ELSE 0 END) AS 部门,
  SUM(CASE WHEN ISNULL(经手人,N'')<>N'' THEN 1 ELSE 0 END) AS 经手人,
  SUM(CASE WHEN ISNULL(退货原因,N'')<>N'' THEN 1 ELSE 0 END) AS 退货原因,
  SUM(CASE WHEN ISNULL(是否已转ERP,N'')<>N'' THEN 1 ELSE 0 END) AS 是否已转ERP,
  SUM(CASE WHEN ISNULL(ERP单号,N'')<>N'' THEN 1 ELSE 0 END) AS ERP单号
FROM dbo.bd_sale_in WHERE ISNULL(asp_cancel,N'N')<>N'Y';