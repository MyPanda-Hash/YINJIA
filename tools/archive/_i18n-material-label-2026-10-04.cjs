const ANCHOR = /(\n\s*\/\*\s*─+\s*特采单两级审批)|\n}\s*$/m
let total = 0
for (const loc of ['en', 'zh-TW']) {
  const file = path.join(ROOT, `frontend/src/i18n/locales/${loc}.js`)
  let src = fs.readFileSync(file, 'utf8')
  const have = new Set()
  for (const m of src.matchAll(/^\s*'((?:[^'\\]|\\.)*)'\s*:/gm)) have.add(m[1].replace(/\\'/g, "'"))
  const add = Object.entries(T).filter(([k]) => !have.has(k))
  if (!add.length) { console.log(`- ${loc}: 无缺失,跳过`); continue }
  const indent = (src.match(/\n(\s+)'/) || [, '    '])[1]
  const q = (s) => (s.includes("'") ? `"${s}"` : `'${s}'`)
  const lines = add.map(([k, [en, tw]]) => `${indent}${q(k)}: ${q(loc === 'en' ? en : tw)},`).join('\n')
  // 插在 biz 段内一个稳定锚点:第一条 `'子件':` 之前(每个包都有它,位置靠前、易核对)
  const anchorIdx = src.search(/^\s*'子件'\s*:/m)
  if (anchorIdx < 0) { console.error(`✗ ${loc}: 找不到插入锚点 '子件'`); process.exit(1) }
  src = src.slice(0, anchorIdx) + lines + '\n' + src.slice(anchorIdx)
  fs.writeFileSync(file, src, 'utf8')
  total += add.length
  console.log(`+ ${loc}: 补 ${add.length} 条`)
}
console.log(`完成:共补 ${total} 条(en + zh-TW);其余 8 语言走机翻兜底`)
