const ANCHOR = /(\n\s*\/\*\s*─+\s*特采单两级审批)|\n}\s*$/m
let total = 0
for (const loc of ['en', 'zh-TW']) {
  const file = path.join(ROOT, `frontend/src/i18n/locales/${loc}.js`)
  let src = fs.readFileSync(file, 'utf8')
  // ① 先删本轮不再使用的死条目(**逐行按键名过滤**,不用正则拼键 —— 拼键的写法一旦差一个字符
  //    就静默不删,第一次就是这么翻车的:报告"删了 6 条"其实一条没删)
  const obsSet = new Set(OBSOLETE)
  const srcLines = src.split('\n')
  const kept = srcLines.filter((line) => {
    const m = line.match(/^\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*:/)
    if (!m) return true
    const key = String(m[1] ?? m[2] ?? '').replace(/\\'/g, "'").replace(/\\"/g, '"')
    return !obsSet.has(key)
  })
  const removed = srcLines.length - kept.length
  if (removed) {
    const keptSet = new Set(kept)
    for (const l of srcLines) if (!keptSet.has(l)) console.log(`    − 删除: ${l.trim().slice(0, 70)}`)
  }
  src = kept.join('\n')
  const have = new Set()
  for (const m of src.matchAll(/^\s*'((?:[^'\\]|\\.)*)'\s*:/gm)) have.add(m[1].replace(/\\'/g, "'"))
  const add = Object.entries(T).filter(([k]) => !have.has(k))
  if (!add.length) { console.log(`- ${loc}: 无缺失(删死条目 ${removed} 条)`); fs.writeFileSync(file, src, 'utf8'); continue }
  const indent = (src.match(/\n(\s+)'/) || [, '    '])[1]
  const q = (s) => (s.includes("'") ? `"${s}"` : `'${s}'`)
  const lines = add.map(([k, [en, tw]]) => `${indent}${q(k)}: ${q(loc === 'en' ? en : tw)},`).join('\n')
  // 插在 biz 段内一个稳定锚点:第一条 `'子件':` 之前(每个包都有它,位置靠前、易核对)
  const anchorIdx = src.search(/^\s*'子件'\s*:/m)
  if (anchorIdx < 0) { console.error(`✗ ${loc}: 找不到插入锚点 '子件'`); process.exit(1) }
  src = src.slice(0, anchorIdx) + lines + '\n' + src.slice(anchorIdx)
  fs.writeFileSync(file, src, 'utf8')
  total += add.length
  // 写完**回读自检**:死条目必须真的不在文件里了(这个脚本第一版就是"报删了、其实没删")
  const back = fs.readFileSync(file, 'utf8')
  const stillThere = OBSOLETE.filter((k) => new RegExp(`^\\s*['"]${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]\\s*:`, 'm').test(back))
  const missingNew = Object.keys(T).filter((k) => !back.includes(`'${k}'`) && !back.includes(`"${k}"`))
  console.log(`+ ${loc}: 补 ${add.length} 条 / 删死条目 ${removed} 条 | 回读:死条目残留 ${stillThere.length} 条、新词条缺失 ${missingNew.length} 条`)
  if (stillThere.length) console.error(`   ✗ 死条目仍在:${stillThere.join('、')}`)
  if (missingNew.length) console.error(`   ✗ 新词条没写进去:${missingNew.join('、')}`)
}
console.log(`完成:共补 ${total} 条(en + zh-TW);其余 8 语言走机翻兜底`)
