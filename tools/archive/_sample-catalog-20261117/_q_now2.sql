SET NOCOUNT ON;
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH AS len, ORDINAL_POSITION AS pos
FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='qc_sample_reg' ORDER BY ORDINAL_POSITION;
SELECT COUNT(*) AS rows_all, SUM(CASE WHEN asp_cancel = '1' THEN 1 ELSE 0 END) AS cancelled FROM qc_sample_reg;
SELECT * FROM qc_sample_reg WHERE ISNULL(asp_cancel,'0') <> '1' ORDER BY id;
