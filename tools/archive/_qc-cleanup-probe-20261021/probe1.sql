UNION ALL SELECT 'qc_insp_detail', COUNT(*) FROM qc_insp_detail
UNION ALL SELECT 'qc_catalog', COUNT(*) FROM qc_catalog
UNION ALL SELECT 'qc_catalog_detail', COUNT(*) FROM qc_catalog_detail
UNION ALL SELECT 'qc_insp_rec', COUNT(*) FROM qc_insp_rec
UNION ALL SELECT 'qc_return', COUNT(*) FROM qc_return
UNION ALL SELECT 'qc_return_detail', COUNT(*) FROM qc_return_detail
UNION ALL SELECT 'sl_recv', COUNT(*) FROM sl_recv
UNION ALL SELECT 'sl_recv_detail', COUNT(*) FROM sl_recv_detail
UNION ALL SELECT 'bd_purchase_in', COUNT(*) FROM bd_purchase_in
UNION ALL SELECT 'bl_purchase_in', COUNT(*) FROM bl_purchase_in
UNION ALL SELECT 'form_flow_link', COUNT(*) FROM form_flow_link;

SELECT '=== qc_insp ===' AS x;
SELECT TOP 50 * FROM qc_insp ORDER BY 单据日期 DESC, id DESC;

