SELECT N'S1-13: RD_* 物理表列名含 编码/受控/履历/章/version' AS sec,
       TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME LIKE 'rd[_]%'
  AND (COLUMN_NAME LIKE N'%编码%' OR COLUMN_NAME LIKE N'%受控%' OR COLUMN_NAME LIKE N'%履历%'
       OR COLUMN_NAME LIKE N'%章%' OR COLUMN_NAME LIKE N'%版本%' OR COLUMN_NAME LIKE N'%version%'
       OR COLUMN_NAME LIKE N'%code%')
ORDER BY TABLE_NAME, COLUMN_NAME;
GO
SELECT N'S1-14: RD_SPEC_DOC/RD_ASM_PROC/RD_INSP_PLAN 头表全列' AS sec,
       TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME IN ('rd_spec_doc_head','rd_asm_proc_head','rd_insp_plan_head','rd_asm_bom_head',
                     'rd_spec_doc_detail','rd_asm_proc_detail','rd_insp_plan_detail')
ORDER BY TABLE_NAME, ORDINAL_POSITION;
GO
SELECT N'S1-15: RD_* 相关全部表名' AS sec, TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME LIKE 'rd[_]%' OR TABLE_NAME LIKE '%spec%' OR TABLE_NAME LIKE '%asm%'
   OR TABLE_NAME LIKE '%insp%' ORDER BY TABLE_NAME;
GO
SELECT N'S1-16: 含 修订 字样的表名(规格书修订记录)' AS sec, TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME LIKE N'%revis%' OR TABLE_NAME LIKE N'%history%' OR TABLE_NAME LIKE N'%log%'
   OR TABLE_NAME LIKE N'%record%' ORDER BY TABLE_NAME;
GO
