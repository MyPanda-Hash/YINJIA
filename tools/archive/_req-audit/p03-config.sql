SET NOCOUNT ON;
PRINT N'=== D0. yj_panel 列类型 ===';
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='yj_panel' ORDER BY ORDINAL_POSITION;
GO
PRINT N'=== D1. config 转字符串后含关键词 ===';
SELECT panel_code, panel_name, LEFT(CONVERT(NVARCHAR(MAX), config), 400) AS cfg_head
FROM yj_panel
WHERE CONVERT(NVARCHAR(MAX), config) LIKE N'%受控%' OR CONVERT(NVARCHAR(MAX), config) LIKE N'%变更%'
   OR CONVERT(NVARCHAR(MAX), config) LIKE N'%公差%' OR CONVERT(NVARCHAR(MAX), config) LIKE N'%履历%'
   OR CONVERT(NVARCHAR(MAX), config) LIKE N'%文件编码%' OR CONVERT(NVARCHAR(MAX), config) LIKE N'%提交%';
