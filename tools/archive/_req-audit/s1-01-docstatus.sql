PRINT N'=== [S1-1] yj_doc_status 真实列 ===';
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'yj_doc_status'
ORDER BY ORDINAL_POSITION;
GO
PRINT N'=== [S1-2] yj_doc_status 全部列名(逗号串,便于拼 SQL) ===';
SELECT STRING_AGG(CAST(COLUMN_NAME AS NVARCHAR(200)), N',') AS cols
FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'yj_doc_status';
GO
PRINT N'=== [S1-3] 是否存在 yj_doc_status 表 ===';
SELECT COUNT(*) AS exist_flag FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'yj_doc_status';
GO
PRINT N'=== [S1-4] 所有含 doc_status / status 的表 ===';
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME LIKE '%doc_status%' OR TABLE_NAME LIKE '%docstatus%' OR TABLE_NAME LIKE '%_status%'
ORDER BY TABLE_NAME;
GO
