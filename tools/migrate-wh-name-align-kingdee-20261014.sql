/* ============================================================
   migrate-wh-name-align-kingdee-20261014.sql — 2026-10-14
   仓库名称与金蝶对齐:CP-02 由「B仓」改为「成品B仓」

   背景:拉取 9/1 至今单据后做「审核+记账」排练,产品入库单有 183 张卡在
     `仓库档案不存在:[成品B仓],请先在基础档案-仓库中建立` —— 金蝶侧该仓名叫「成品B仓」,
     而 MES 档案(bs_wh)里同编码 CP-02 叫「B仓」,**名称口径不一致**。
     产成品入库单的行表只有仓库**名称**列(没有仓库编码列),台账按名称解析 ⇒ 直接失败。

   口径:金蝶是出入库单据的真源 ⇒ 档案名向金蝶看齐(这是唯一一处不一致;
     拉取单据里出现的仓库名共 4 个,其余「成品不良品区/恒亿仓/华北工控仓」档案都能命中)。

   幂等(仅当名称仍为旧值时才改);两账套均执行。
   ============================================================ */
SET NOCOUNT ON;
GO
UPDATE bs_wh SET 仓库名称 = N'成品B仓'
 WHERE 仓库编码 = N'CP-02' AND 仓库名称 <> N'成品B仓';
GO
-- 自检:CP-02 必须叫「成品B仓」,且不能因此出现重名
DECLARE @bad int = 0;
IF NOT EXISTS (SELECT 1 FROM bs_wh WHERE 仓库编码 = N'CP-02' AND 仓库名称 = N'成品B仓') SET @bad = @bad + 1;
IF (SELECT COUNT(*) FROM bs_wh WHERE 仓库名称 = N'成品B仓') > 1 SET @bad = @bad + 1;
IF @bad > 0 RAISERROR(N'CP-02 仓库名称对齐自检失败(%d 项)', 16, 1, @bad);
ELSE PRINT N'CP-02 仓库名称已对齐金蝶(成品B仓;幂等)';
GO
