/**
 * inspCommissionVat.js —— 检验委托单「总金额（含增值税6%）」换算(2026-11-16 用户口径)
 *
 * 用户口径:「修改文件的总金额计算方式,将合计收费修改为（总金额（含增值税6%）RMB）。
 *            之后的总金额需要在原基础上增加6%的数值」
 * ⇒ 纸面「合计收费」改名为「总金额（含增值税6%）RMB」,金额 = 行表「收费」合计 × (1 + 6%)。
 *
 * 2026-11-19 用户口径(补):「收费列是一个样/元(图里 100 元 = 一个样品检验的金额),所以总金额
 *   必须乘上『样品数量』」——
 * ⇒ **总金额(含税) = 行表「收费」合计 × 样品数量 × (1 + 6%)**。
 *    行表「收费」仍是**一个样/元**的单价(行表显示不动);「样品数量」是表头文本,解析规则见 sampleCountOf。
 *
 * 为什么要单独成模块:金额换算是**纯算术**,放进 .vue 里只能靠"读源码断言"这种弱测试;
 *   外置后可以对真实数字做单测(600→636.00、123.45→130.86 这类四舍五入边界,以及 ×10 个样的 6360.00)。
 * 口径:按**分**四舍五入(`Math.round(x*100)/100`),避免 600×1.06 = 636.0000000000001 的浮点尾差。
 */

/** 增值税率:6% */
export const VAT_RATE = 0.06

/** 非数字/空值按 0 处理(不让脏值把纸面算成 NaN) */
function numOf(net) {
  const n = Number(net)
  return Number.isFinite(n) ? n : 0
}

/**
 * 样品数量归一:非有限数 / ≤0 一律按 1 件。
 * 理由:数量是**乘数**,脏值若按 0 算会把整单总金额清零(纸面看起来像"金额丢了");
 *   而"没有明确数量"这件事在业务上就等于"按一个样计",与 2026-11-16 的旧口径一致。
 */
function qtyOf(qty) {
  const n = numOf(qty)
  return n > 0 ? n : 1
}

/**
 * 「样品数量」(表头**文本**字段) → 件数(正数)。
 *
 * 用户口径(2026-11-19):收费列是「一个样/元」⇒ 总金额要乘样品数量;而纸样允许
 * `样品数量` 写成「2L/3支」这类多段文本(yj_field 注释即此口径)⇒ 必须定一套解析规则:
 *   · 空 / 非数字 / ≤0 → **1**(不猜:没有明确数量就按"一个样"计,总金额退回 2026-11-16 的旧口径);
 *   · 纯数字 `10` → 10;
 *   · 数字 + **计件单位**(个/件/支/只/pcs,允许中间空格、大小写) → 取数字部分(`5 PCS`→5、`10个`→10);
 *   · 数字 + **容积单位**(L / ml)→ **1**:`2L`、`500ml` 说的是**样品体积**(2 升水样 = 一份样品),
 *     不是件数;按 2 件会多收一倍(用户 2026-11-19 明确纠正过这条);
 *   · 含斜杠/多段写法(`2L/3支`、`2/3`) → **1**:同一份委托按**一个样品**计,不猜拆分
 *     (拆错会把金额成倍放大或缩小,而纸面没有任何"按几份计"的提示可校对;宁可退回旧口径)。
 *     ⚠ 要让多段写法按件数算,必须先由业务给出明确口径,再连同本函数与单测一起改。
 */
const SAMPLE_UNIT_RE = /^(\d+(?:\.\d+)?)\s*(个|件|支|只|pcs?)$/i

/** 「样品数量」文本 → 件数(空/脏值/容积/多段一律 1 件;规则见上方注释) */
export function sampleCountOf(raw) {
  const text = String(raw ?? '').trim()
  if (!text) return 1
  if (/^\d+(?:\.\d+)?$/.test(text)) return qtyOf(text)
  const m = SAMPLE_UNIT_RE.exec(text)
  if (m) return qtyOf(m[1])
  return 1
}

/**
 * 净额 → 含税总额(数值,保留两位小数口径) = net × qty × (1 + 6%)。
 *
 * @param {number|string} net 行表「收费」合计(**一个样/元**的单价合计,不是总价)
 * @param {number|string} [qty=1] 样品数量(件);缺省 / 脏值 / ≤0 一律按 1 件
 *   ⇒ **不传 qty 时行为与 2026-11-16 口径完全一致**(向后兼容)。
 */
export function withVat(net, qty = 1) {
  return Math.round(numOf(net) * qtyOf(qty) * (1 + VAT_RATE) * 100) / 100
}

/** 净额 → 含税总额文本(两位小数;纸面显示与表头「合计收费」同源,同样支持第二参数 qty) */
export function vatTotalText(net, qty = 1) {
  return withVat(net, qty).toFixed(2)
}
